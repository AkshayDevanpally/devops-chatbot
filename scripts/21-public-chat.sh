#!/usr/bin/env bash
# Phase 9b: live chat on the public (Netlify) site, through the Raspberry Pi with Tailscale Funnel.
#
#   ./scripts/21-public-chat.sh setup           # secrets, then set up the Pi (Pi's sudo password; Tailscale login once)
#   ./scripts/21-public-chat.sh netlify         # write the chat routes into netlify.toml (after setup)
#   ./scripts/21-public-chat.sh netlify-secret  # print the value for Netlify's QWENOPS_PROXY_SECRET (run it yourself)
#   ./scripts/21-public-chat.sh test [SITE]     # checks against the Funnel address (and SITE, e.g. https://x.netlify.app)
#   ./scripts/21-public-chat.sh status
#   ./scripts/21-public-chat.sh off             # close public chat (Funnel off); setup turns it on again
#
# Path: visitor → Netlify (signs each request) → Funnel → Pi nginx (checks the signature, chat paths only,
# limits) → prod chat-api (edge secret: public visitor = stricter limits, guest only, shorter replies).
# Secrets: secret public-chat in chatbot-prod (NETLIFY_SECRET, PUBLIC_URL) and EDGE_SECRET in chat-api-secrets.
set -euo pipefail
cd "$(dirname "$0")/.."
PI="${PI:-rasppi@192.168.1.104}"
NS=chatbot-prod
REMOTE=qwenops-public-install
SERVER_IP=$(ip -4 route get 1.1.1.1 | sed -n 's/.* src \([0-9.]*\).*/\1/p')

secret() { kubectl -n $NS get secret "$1" -o "jsonpath={.data.$2}" 2>/dev/null | base64 -d; }

setup() {
  echo "==> secrets"
  if ! kubectl -n $NS get secret public-chat >/dev/null 2>&1; then
    kubectl -n $NS create secret generic public-chat --from-literal=NETLIFY_SECRET="$(openssl rand -hex 32)" >/dev/null
    echo "    made the Netlify signing secret (secret public-chat)"
  fi
  if [[ -z $(secret chat-api-secrets EDGE_SECRET) ]]; then
    kubectl -n $NS patch secret chat-api-secrets -p "{\"stringData\":{\"EDGE_SECRET\":\"$(openssl rand -hex 32)\"}}" >/dev/null
    echo "    added EDGE_SECRET to chat-api-secrets; restarting prod chat-api to read it"
    kubectl -n $NS rollout restart deployment/chat-api >/dev/null
    kubectl -n $NS rollout status deployment/chat-api --timeout=180s
  fi
  tmp=$(mktemp -d); chmod 700 "$tmp"; trap 'rm -rf "$tmp"' EXIT
  mkdir "$tmp/public"; cp pi/public-setup.sh "$tmp/"; cp pi/public/verify.js "$tmp/public/"
  (umask 077
   printf 'SERVER_IP=%s\nEDGE_SECRET=%s\n' "$SERVER_IP" "$(secret chat-api-secrets EDGE_SECRET)" > "$tmp/public.env"
   secret public-chat NETLIFY_SECRET > "$tmp/netlify.secret")
  echo "==> copying to $PI and setting it up (the Pi asks for its sudo password; Tailscale may show a login link)"
  ssh -o BatchMode=yes "$PI" "rm -rf ~/$REMOTE && mkdir -m 700 ~/$REMOTE"
  scp -q -r "$tmp"/* "$PI:$REMOTE/"
  # The secrets exist on the Pi's home folder only until setup has installed them.
  ssh -t "$PI" "sudo bash ~/$REMOTE/public-setup.sh install; rc=\$?; rm -rf ~/$REMOTE; exit \$rc"
  url=$(public_url_from_pi)
  [[ -n $url ]] || { echo "couldn't read the Funnel address from the Pi"; exit 1; }
  kubectl -n $NS patch secret public-chat -p "{\"stringData\":{\"PUBLIC_URL\":\"$url\"}}" >/dev/null
  echo
  echo "Public chat gateway: $url"
  echo "Next: ./scripts/21-public-chat.sh netlify, then set QWENOPS_PROXY_SECRET in Netlify (see README)."
}

public_url_from_pi() {
  ssh -o BatchMode=yes "$PI" "tailscale status --json" 2>/dev/null \
    | python3 -I -c 'import json,sys; n=json.load(sys.stdin)["Self"]["DNSName"].rstrip("."); print("https://"+n if n else "")' 2>/dev/null || true
}

netlify() {
  url=$(secret public-chat PUBLIC_URL); [[ -n $url ]] || { echo "run setup first"; exit 1; }
  python3 -I - "$url" <<'PY'
import re, sys
url = sys.argv[1]
p = "netlify.toml"; s = open(p).read()
start, end = "# --- public chat: generated by scripts/21-public-chat.sh netlify ---", "# --- end public chat ---"
block = [start, "# Netlify signs each request with QWENOPS_PROXY_SECRET (set in Netlify); the Pi refuses anything unsigned."]
for path in ("/api/chat", "/api/history", "/api/status", "/api/wake"):
    block += ["[[redirects]]", f'  from = "{path}"', f'  to = "{url}{path}"', "  status = 200", "  force = true",
              '  signed = "QWENOPS_PROXY_SECRET"', ""]
block.append(end)
text = "\n".join(block)
if start in s:
    s = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda m: text, s, flags=re.S)
else:   # before the catch-all /api/* rule: the first matching rule wins
    s = s.replace("# Nothing serves /api here", text + "\n\n# Nothing else serves /api here", 1)
s = re.sub(r'PUBLIC_CHAT = "\w+"', 'PUBLIC_CHAT = "on"', s)
open(p, "w").write(s)
print(f"netlify.toml: chat routes → {url}, PUBLIC_CHAT = on. Commit and push to publish.")
PY
}

sign() {   # a Netlify-style signature (JWS, HS256) for testing
  python3 -I - "$1" <<'PY'
import base64, hashlib, hmac, json, sys, time
b = lambda x: base64.urlsafe_b64encode(x).rstrip(b"=").decode()
h = b(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
p = b(json.dumps({"iss": "netlify", "exp": int(time.time()) + 120, "site_url": "test"}).encode())
print(f"{h}.{p}." + b(hmac.new(sys.argv[1].encode(), f"{h}.{p}".encode(), hashlib.sha256).digest()))
PY
}

test_public() {
  url=$(secret public-chat PUBLIC_URL); [[ -n $url ]] || { echo "run setup first"; exit 1; }
  tok=$(sign "$(secret public-chat NETLIFY_SECRET)")
  fail=0; ok() { echo "PASS  $1"; }; bad() { echo "FAIL  $1"; fail=1; }
  code() { curl -s -m 20 -o /dev/null -w '%{http_code}' "$@"; }
  [[ $(code "$url/api/status") == 403 ]] && ok "Funnel address refuses unsigned requests" || bad "unsigned request not refused"
  [[ $(code -H "X-Nf-Sign: $(sign wrong-secret)" "$url/api/status") == 403 ]] && ok "wrong signature refused" || bad "wrong signature not refused"
  st=$(curl -s -m 20 -H "X-Nf-Sign: $tok" "$url/api/status")
  [[ $st == *'"ready"'* ]] && ok "signed /api/status reaches prod: $st" || bad "signed status: $st"
  [[ $(code -H "X-Nf-Sign: $tok" "$url/api/pulse") == 404 ]] && ok "other paths refused on the Pi (404)" || bad "/api/pulse not refused"
  h=$(curl -s -m 20 -H "X-Nf-Sign: $tok" "$url/api/history")
  [[ $h == *'"public":true'* || $h == *'"public": true'* ]] && ok "prod treats it as a public visitor (guest, nothing stored)" || bad "history: $h"
  out=$(curl -sN -m 90 -H "X-Nf-Sign: $tok" -H 'Content-Type: application/json' -d '{"message":"Say hello in five words."}' "$url/api/chat")
  [[ $out == *'"token"'* && $out == *"event: done"* ]] && ok "chat streams a full reply through the Funnel" || bad "chat: ${out:0:200}"
  if [[ -n ${1:-} ]]; then
    site=${1%/}
    st=$(curl -s -m 30 "$site/api/status")
    [[ $st == *'"ready"'* ]] && ok "$site/api/status through Netlify: $st" || bad "through Netlify: $st (QWENOPS_PROXY_SECRET set in Netlify? routes pushed?)"
    out=$(curl -sN -m 90 -c /dev/null -H 'Content-Type: application/json' -d '{"message":"Say hello in five words."}' "$site/api/chat")
    [[ $out == *"event: done"* ]] && ok "chat through Netlify streams a full reply" || bad "chat through Netlify: ${out:0:200}"
    [[ $(code "$site/api/pulse") == 404 ]] && ok "$site/api/pulse is not available (404)" || bad "$site/api/pulse answered"
  fi
  return $fail
}

case "${1:-}" in
  setup) setup ;;
  netlify) netlify ;;
  netlify-secret) secret public-chat NETLIFY_SECRET; echo ;;
  test) test_public "${2:-}" ;;
  status)
    echo "Funnel address: $(secret public-chat PUBLIC_URL)"
    ssh -o BatchMode=yes "$PI" "tailscale funnel status 2>&1 | sed -n '1,8p'; systemctl is-active nginx tailscaled | paste -sd' '" ;;
  off) ssh -t "$PI" "sudo tailscale serve reset" && echo "Public chat closed (Funnel off)." ;;
  *) sed -n '2,13p' "$0"; exit 2 ;;
esac
