#!/usr/bin/env python3
"""Build the public showcase for Netlify (Phase 9) into dist/. Standard library only.

    python3 -I scripts/netlify-build.py          (Netlify runs this; see netlify.toml)

- copies the pages (app-ui/public)
- builds the Error Journal data from docs/ (the same generator as the ui image; it redacts
  private IPs, keys, long hex strings, passwords and emails)
- adds the snapshot from prod (app-ui/showcase/, made by scripts/20-showcase.sh snapshot)
- writes config.js with window.SHOWCASE set, so no page calls an API
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "app-ui" / "public"
SNAPSHOT = ROOT / "app-ui" / "showcase"
DIST = ROOT / "dist"
NEEDED = ["meta.json", "pulse-15m.json", "pulse-1h.json", "pulse-6h.json", "capacity.json", "backups.json"]


def main() -> None:
    missing = [f for f in NEEDED if not (SNAPSHOT / f).is_file()]
    if missing:
        sys.exit(f"missing snapshot files in app-ui/showcase: {', '.join(missing)} (run: make showcase-snapshot)")
    taken = json.loads((SNAPSHOT / "meta.json").read_text())["taken"]
    # Phase 9b: with PUBLIC_LIVE=on (netlify.toml) the pages use the home server through the Pi.
    live = os.environ.get("PUBLIC_LIVE", "off") == "on"

    if DIST.exists():
        shutil.rmtree(DIST)
    shutil.copytree(PUBLIC, DIST)
    shutil.copytree(SNAPSHOT, DIST / "showcase")

    subprocess.run([sys.executable, "-I", str(ROOT / "app-ui" / "journal" / "build_journal.py"),
                    str(ROOT / "docs"), str(DIST / "journal" / "journal.json")], check=True)

    (DIST / "theme.json").write_text(json.dumps({"color": "teal", "env": "public"}) + "\n")
    (DIST / "config.js").write_text(
        "// Generated by scripts/netlify-build.py: the public showcase has no backend.\n"
        'window.API_BASE = "";\n'
        f"window.SHOWCASE = {json.dumps({'taken': taken, 'live': live})};\n")
    (DIST / "healthz").write_text("ok\n")
    (DIST / "showcase" / "no-api.json").write_text(
        json.dumps({"showcase": True, "detail": "This public copy has no backend."}) + "\n")

    files = sum(1 for p in DIST.rglob("*") if p.is_file())
    print(f"built dist/: {files} files, snapshot taken {taken}, live {'on' if live else 'off'}")


if __name__ == "__main__":
    main()
